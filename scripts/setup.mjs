// Runs after `npm install`. Creates .env.local with a random session secret for local use.
// Skipped on hosts such as Vercel: there, set SESSION_SECRET in the dashboard instead
// (a secret generated at build time would not match between the edge and server code).
import { existsSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
if (process.env.VERCEL || process.env.CI) {
  console.log("Skipping .env.local (hosted build). Set SESSION_SECRET in your host's environment variables.");
} else if (!existsSync(".env.local")) {
  writeFileSync(".env.local", `# Generated by scripts/setup.mjs. Never commit this file.\nSESSION_SECRET=${randomBytes(32).toString("hex")}\n\n# Optional: real SMS and WhatsApp through Twilio. See .env.example\n`);
  console.log("Created .env.local with a new SESSION_SECRET");
}
